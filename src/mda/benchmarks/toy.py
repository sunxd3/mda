"""End-to-end scalar law-discovery demo, including optional live LLM proposals."""

from __future__ import annotations

import argparse
import json

import numpy as np

from mda.agent import AgentConfig, ModelDiscoveryAgent
from mda.expressions import SymbolicRegressionProposer, canonical_expression, compile_expression
from mda.likelihoods import DeterministicGaussianLikelihood
from mda.openai_client import OpenAIJSONClient
from mda.smc import SMCConfig
from mda.types import CandidateModel, Datum, UniformPrior


def _model(name: str, expression: str, names: tuple[str, ...]) -> CandidateModel:
    return CandidateModel(
        name=name,
        structure=canonical_expression(expression),
        prior=UniformPrior(names, np.full(len(names), -5.0), np.full(len(names), 5.0)),
        predict=compile_expression(expression, ("x",), names),
    )


def default_models() -> list[CandidateModel]:
    return [
        _model("constant", "a", ("a",)),
        _model("linear", "a + b*x", ("a", "b")),
        _model("quadratic", "a + b*x + c*x**2", ("a", "b", "c")),
        _model("exponential", "a*exp(b*x)", ("a", "b")),
    ]


def truth(x: float) -> float:
    return 0.25 + 1.5 * x**2


def run_demo(*, live: bool = False, model: str = "gpt-5.6-luna", seed: int = 7) -> dict:
    rng = np.random.default_rng(seed)
    initial_x = [-1.0, 0.0, 1.0]
    initial_data = [Datum(x, np.asarray(truth(x) + rng.normal(0, 0.05))) for x in initial_x]
    proposer = (
        SymbolicRegressionProposer(OpenAIJSONClient(model=model), variable_names=("x",))
        if live
        else None
    )
    agent = ModelDiscoveryAgent(
        context="A scalar response is generated by a smooth, low-order scientific law y=f(x).",
        initial_data=initial_data,
        initial_models=[] if live else default_models(),
        proposer=proposer,
        likelihood=DeterministicGaussianLikelihood(0.05),
        actions=np.linspace(-3.0, 3.0, 13).tolist(),
        observation_covariance=0.05**2,
        config=AgentConfig(
            model_cap=6,
            error_threshold=0.08,
            occam_penalty=0.5,
            smc=SMCConfig(parameter_particles=300, rejuvenation_steps=3),
        ),
        seed=seed,
    )
    selected = []
    for _ in range(3):
        action = float(agent.design())
        selected.append(action)
        agent.update_state(action, np.asarray(truth(action) + rng.normal(0, 0.05)))
    query = np.linspace(-3.5, 3.5, 31)
    predicted = np.asarray([agent.predict(float(x), "map") for x in query], dtype=float).reshape(-1)
    actual = np.asarray([truth(float(x)) for x in query])
    nmse = float(np.mean((predicted - actual) ** 2) / np.var(actual))
    fit = agent.belief.map_fit
    return {
        "model": fit.model.name,
        "expression": fit.model.structure,
        "parameters": dict(zip(fit.model.prior.names, fit.parameters.map_parameters.tolist(), strict=True)),
        "posterior_probability": float(agent.belief.model_weights[agent.belief.map_index]),
        "selected_experiments": selected,
        "held_out_nmse": nmse,
    }


def main() -> None:
    parser = argparse.ArgumentParser()
    parser.add_argument("--live", action="store_true", help="use OpenAI for model proposals")
    parser.add_argument("--model", default="gpt-5.6-luna")
    parser.add_argument("--seed", type=int, default=7)
    args = parser.parse_args()
    print(json.dumps(run_demo(live=args.live, model=args.model, seed=args.seed), indent=2))


if __name__ == "__main__":
    main()
